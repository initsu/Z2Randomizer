using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace CoreSourceGenerator;

/// <summary>
/// Generates checked property implementations for classes marked with
/// <c>Z2Randomizer.RandomizerCore.Diagnostics.CheckedInitializationAttribute</c>.
/// It is used by <c>RandomizerCore/RandomizerProperties.cs</c>, the resolved
/// settings snapshot produced by <c>RandomizerConfiguration.Export</c> and read
/// throughout ROM generation.
/// </summary>
/// <remarks>
/// Export resolves some settings from other, already-resolved properties. Reading
/// an unassigned property would otherwise return its CLR default, such as
/// <c>false</c>, and silently make the result depend on assignment order.
/// <para>
/// Declare these properties as <c>public partial T Name { get; set; }</c>. The
/// generated setter records assignment under <c>DEBUG</c>, and the getter throws
/// an <c>InvalidOperationException</c> naming the property if no setter has run.
/// Explicitly assigning <c>false</c>, zero, or <c>null</c> still counts as an
/// assignment. Release accessors contain no tracking fields or checks.
/// </para>
/// <para>
/// Ordinary auto-properties with explicit declaration initializers are intentional
/// defaults and are left alone; an auto-property without one must be partial or
/// produces build error <c>Z2R001</c>. For resolved arrays, build the contents
/// locally and assign the completed array to a checked property: this mechanism
/// tracks property assignment, not initialization of individual array elements.
/// Database and JSON mapping attributes do not affect these checks.
/// </para>
/// </remarks>
[Generator]
public sealed class CheckedInitializationGenerator : IIncrementalGenerator
{
#pragma warning disable RS2008 // This repo-local generator is not released as an analyzer package.
    private static readonly DiagnosticDescriptor MissingPartial = new(
        "Z2R001", "Property initialization must be explicit",
        "Property '{0}' must be partial for checked initialization, or declare an explicit default",
        "Initialization", DiagnosticSeverity.Error, isEnabledByDefault: true);
#pragma warning restore RS2008

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var classes = context.SyntaxProvider.ForAttributeWithMetadataName(
            "Z2Randomizer.RandomizerCore.Diagnostics.CheckedInitializationAttribute",
            static (node, _) => node is ClassDeclarationSyntax,
            static (ctx, _) => ctx);

        context.RegisterSourceOutput(classes, static (output, ctx) => Generate(output, ctx));
    }

    private static void Generate(SourceProductionContext output, GeneratorAttributeSyntaxContext context)
    {
        var declaration = (ClassDeclarationSyntax)context.TargetNode;
        var type = (INamedTypeSymbol)context.TargetSymbol;
        var source = new StringBuilder();
        source.AppendLine("// <auto-generated/>");
        source.AppendLine("#nullable enable");
        source.AppendLine($"namespace {type.ContainingNamespace};");
        source.AppendLine($"public partial class {type.Name}");
        source.AppendLine("{");

        foreach (var property in declaration.Members.OfType<PropertyDeclarationSyntax>())
        {
            bool isAutoProperty = property.AccessorList is { } accessors
                && accessors.Accessors.All(accessor => accessor.Body == null && accessor.ExpressionBody == null);
            if (!isAutoProperty || property.Initializer != null)
                continue;

            if (!property.Modifiers.Any(SyntaxKind.PartialKeyword))
            {
                output.ReportDiagnostic(Diagnostic.Create(MissingPartial, property.Identifier.GetLocation(), property.Identifier.Text));
                continue;
            }

            var symbol = (IPropertySymbol)context.SemanticModel.GetDeclaredSymbol(property)!;
            string propertyType = symbol.Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat
                .WithMiscellaneousOptions(SymbolDisplayMiscellaneousOptions.IncludeNullableReferenceTypeModifier));
            string name = property.Identifier.Text;
            string storage = $"__{name}Value";
            string assigned = $"__{name}Assigned";

            source.AppendLine($"    private {propertyType} {storage} = default!;");
            source.AppendLine("#if DEBUG");
            source.AppendLine($"    private bool {assigned};");
            source.AppendLine("#endif");
            source.AppendLine($"    public partial {propertyType} {name}");
            source.AppendLine("    {");
            source.AppendLine("        get");
            source.AppendLine("        {");
            source.AppendLine("#if DEBUG");
            source.AppendLine($"            if (!{assigned})");
            source.AppendLine($"                throw new global::System.InvalidOperationException(\"{type.Name}.{name} was read before it was assigned.\");");
            source.AppendLine("#endif");
            source.AppendLine($"            return {storage};");
            source.AppendLine("        }");
            source.AppendLine("        set");
            source.AppendLine("        {");
            source.AppendLine($"            {storage} = value;");
            source.AppendLine("#if DEBUG");
            source.AppendLine($"            {assigned} = true;");
            source.AppendLine("#endif");
            source.AppendLine("        }");
            source.AppendLine("    }");
        }

        source.AppendLine("}");
        output.AddSource($"{type.Name}.CheckedInitialization.g.cs", source.ToString());
    }
}
